export type Messages = MessageShape<typeof en>;

export const messages: Record<ResolvedInterfaceLanguage, Messages> = {
  en,
  'zh-Hans': zhHans,
};

type LeafKeys<T> = {
  [K in keyof T & string]: T[K] extends string ? K : T[K] extends object ? `${K}.${LeafKeys<T[K]>}` : never;
}[keyof T & string];

export type MessageKey = LeafKeys<Messages>;

export function resolveInterfaceLanguage(
  preference: InterfaceLanguage,
  browserLanguage = typeof navigator === 'undefined' ? 'en' : navigator.language,
): ResolvedInterfaceLanguage {
  if (preference === 'zh-Hans' || preference === 'en') return preference;
  return browserLanguage.toLowerCase().startsWith('zh') ? 'zh-Hans' : 'en';
}

export function getMessages(language: ResolvedInterfaceLanguage): Messages {
  return messages[language];
}

export function readMessage(messagesForLanguage: Messages, key: MessageKey): string {
  return key.split('.').reduce<unknown>((value, segment) => {
    if (value && typeof value === 'object' && segment in value) {
      return (value as Record<string, unknown>)[segment];
    }
    return undefined;
  }, messagesForLanguage) as string;
}

export function interpolate(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
